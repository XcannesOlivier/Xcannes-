/**
 * useWalletModalProps
 * -------------------
 * Centralise la construction des props partagées entre les versions desktop
 * (inline / aside) et mobile (portalisées) des modales du wallet.
 *
 * L'objectif est d'éliminer la duplication : chaque jeu de props est calculé
 * une seule fois, puis consommé par WalletDesktopModals et WalletMobileModals.
 */

import { useMemo } from 'react';

export function useWalletModalProps({
  // --- identité du wallet ---
  wallet,
  walletAddresses,
  switchWallet,
  isConnected,
  isWalletActivated,
  hasOnChainRlusd,
  walletLabel,
  walletHasCustomLabel,
  renderWalletMeta,
  connect,

  // --- actions / state machines ---
  activeAction,
  setActiveAction,

  // --- Send ---
  qrSizingVariant,
  selectableTokens,
  augmentedTokens,
  selectedSendToken,
  sendFxInfo,
  setSendAssetKey,
  sendAmount,
  setSendAmount,
  sendPaymentRequest,
  setSendPaymentRequest,
  moonpaySellRequest,
  selectLabelByAssetKey,
  selectLabelRightByAssetKey,
  selectIconByAssetKey,
  selectLabelMobileByAssetKey,
  savedAddresses,
  sendDestination,
  setSendDestination,
  sendDestinationLabel,
  setSendDestinationLabel,
  setQrScannerOpen,
  handlePaymentRequestScan,
  handleSendSubmit,
  sendProcessing,

  // --- Receive ---
  receiveTab,
  setReceiveTab,
  handleCopyAddress,
  requestAmount,
  setRequestAmount,
  requestCurrency,
  setRequestCurrency,
  requestMemo,
  setRequestMemo,
  rlusdPerUnitRates,
  rlusdPerUnitSources,

  // --- Swap / Convert ---
  swapDefaultView,
  swapLockedView,
  swapCurrencyOptionsForModal,
  convertBaseCurrency,
  setConvertBaseCurrency,
  convertQuoteCurrency,
  setConvertQuoteCurrency,
  convertAmount,
  setConvertAmount,
  convertProcessing,
  handleInstallRequiredTrustline,
  effectiveRefreshCurrencyLines,
  effectiveCurrencyLinesError,
  effectiveCurrencyLinesSummary,
  effectiveCurrencyLines,
  currencyLineCode,
  setCurrencyLineCode,
  currencyLineAllocatedRlusd,
  setCurrencyLineAllocatedRlusd,
  handleUpsertCurrencyLine,
  handleDemoConvert,

  // --- Cash ---
  cashModalTab,
  setCashModalTab,
  cashBuyPrefill,
  setCashBuyPrefill,
  cashSellSelectTitleOverride,
  setCashSellSelectTitleOverride,
  cashSellDestinationMode,
  setCashSellDestinationMode,

  // --- Activation ---
  showActivationModal,
  setShowActivationModal,
  handleActivationSendFromWallet,
  handleActivationRequestFromThirdParty,
  handleActivationBuyViaMoonpay,

  // --- Activation Request ---
  showActivationRequestModal,
  setShowActivationRequestModal,

  // --- Info ---
  walletInfoOpen,
  setWalletInfoOpen,

  // --- Statements ---
  displayTokensWithCurrencyLines,
  backendWalletAddress,
  usdRates,
  preferredCurrency,
  showGlobalStatement,
  setShowGlobalStatement,
  showCurrencyStatement,
  setShowCurrencyStatement,
  selectedStatementToken,
  setSelectedStatementToken,
  statementBalance,
  highlightTransactionId,

  // --- QR ---
  qrScannerOpen,
  handleAddressScan,

  // --- Toast ---
  toast,
  // --- Reset ---
  resetSendForm,
  resetReceiveForm,
  resetSwapForm,
  resetCashForm,
}) {
  // --- Send modal props ---
  const sendModalProps = useMemo(
    () => ({
      currentWalletAddress: typeof wallet === 'string' ? wallet : wallet?.address || '',
      qrSizingVariant,
      renderWalletMeta,
      augmentedTokens: moonpaySellRequest ? augmentedTokens : selectableTokens,
      selectedSendToken,
      sendFxInfo,
      setSendAssetKey,
      sendAmount,
      setSendAmount,
      sendPaymentRequest,
      moonpaySellRequest,
      selectLabelByAssetKey,
      selectLabelRightByAssetKey,
      selectIconByAssetKey,
      selectLabelMobileByAssetKey,
      savedAddresses,
      sendDestination,
      setSendDestination,
      sendDestinationLabel,
      setSendDestinationLabel,
      setQrScannerOpen,
      handlePaymentRequestScan,
      handleSendSubmit,
      sendProcessing,
      enableSaveAddress: true,
      resetSendForm,
      toast,
    }),
    [
      wallet,
      qrSizingVariant,
      renderWalletMeta,
      augmentedTokens,
      selectableTokens,
      moonpaySellRequest,
      selectedSendToken,
      sendFxInfo,
      setSendAssetKey,
      sendAmount,
      setSendAmount,
      sendPaymentRequest,
      selectLabelByAssetKey,
      selectLabelRightByAssetKey,
      selectIconByAssetKey,
      selectLabelMobileByAssetKey,
      savedAddresses,
      sendDestination,
      setSendDestination,
      sendDestinationLabel,
      setSendDestinationLabel,
      setQrScannerOpen,
      handlePaymentRequestScan,
      handleSendSubmit,
      sendProcessing,
      resetSendForm,
      toast,
    ],
  );

  // --- Receive modal props ---
  const receiveModalProps = useMemo(
    () => ({
      dashboardVariant: 'full',
      receiveTab,
      setReceiveTab,
      renderWalletMeta,
      wallet,
      walletAddresses,
      onSwitchWallet: switchWallet,
      handleCopyAddress,
      requestAmount,
      setRequestAmount,
      requestCurrency,
      setRequestCurrency,
      selectLabelByCurrency: selectLabelByAssetKey,
      selectLabelRightByCurrency: selectLabelRightByAssetKey,
      selectIconByCurrency: selectIconByAssetKey,
      selectLabelMobileByCurrency: selectLabelMobileByAssetKey,
      augmentedTokens: selectableTokens,
      requestMemo,
      setRequestMemo,
      rlusdPerUnitRates,
      rlusdPerUnitSources,
      walletLabel,
    }),
    [
      receiveTab,
      setReceiveTab,
      renderWalletMeta,
      wallet,
      walletAddresses,
      switchWallet,
      handleCopyAddress,
      requestAmount,
      setRequestAmount,
      requestCurrency,
      setRequestCurrency,
      selectLabelByAssetKey,
      selectLabelRightByAssetKey,
      selectIconByAssetKey,
      selectLabelMobileByAssetKey,
      selectableTokens,
      requestMemo,
      setRequestMemo,
      rlusdPerUnitRates,
      rlusdPerUnitSources,
      walletLabel,
    ],
  );

  // --- Swap modal props ---
  const swapModalProps = useMemo(
    () => ({
      renderWalletMeta,
      defaultView: swapDefaultView,
      lockedView: swapLockedView,
      isConnected,
      walletAddress: wallet,
      onConnectWallet: connect,
      onInstallTrustline: handleInstallRequiredTrustline,
      refreshCurrencyLines: effectiveRefreshCurrencyLines,
      currencyLinesError: effectiveCurrencyLinesError,
      currencyLinesSummary: effectiveCurrencyLinesSummary,
      currencyLines: effectiveCurrencyLines,
      swapCurrencyOptions: swapCurrencyOptionsForModal,
      convertBaseCurrency,
      setConvertBaseCurrency,
      convertQuoteCurrency,
      setConvertQuoteCurrency,
      convertAmount,
      setConvertAmount,
      selectLabelByCurrency: selectLabelByAssetKey,
      selectLabelRightByCurrency: selectLabelRightByAssetKey,
      selectIconByCurrency: selectIconByAssetKey,
      selectLabelMobileByCurrency: selectLabelMobileByAssetKey,
      currencyLineCode,
      setCurrencyLineCode,
      currencyLineAllocatedRlusd,
      setCurrencyLineAllocatedRlusd,
      handleUpsertCurrencyLine,
      handleDemoConvert,
      convertProcessing,
      rlusdPerUnitRates,
    }),
    [
      renderWalletMeta,
      swapDefaultView,
      swapLockedView,
      isConnected,
      wallet,
      connect,
      handleInstallRequiredTrustline,
      effectiveRefreshCurrencyLines,
      effectiveCurrencyLinesError,
      effectiveCurrencyLinesSummary,
      effectiveCurrencyLines,
      swapCurrencyOptionsForModal,
      convertBaseCurrency,
      setConvertBaseCurrency,
      convertQuoteCurrency,
      setConvertQuoteCurrency,
      convertAmount,
      setConvertAmount,
      selectLabelByAssetKey,
      selectLabelRightByAssetKey,
      selectIconByAssetKey,
      selectLabelMobileByAssetKey,
      currencyLineCode,
      setCurrencyLineCode,
      currencyLineAllocatedRlusd,
      setCurrencyLineAllocatedRlusd,
      handleUpsertCurrencyLine,
      handleDemoConvert,
      convertProcessing,
      rlusdPerUnitRates,
    ],
  );

  // --- Cash modal props ---
  const cashModalProps = useMemo(
    () => ({
      cashModalTab,
      setCashModalTab,
      walletLabel,
      preferredFiatCurrency: preferredCurrency,
      rlusdPerUnitRates,
      selectLabelByCurrency: selectLabelByAssetKey,
      selectLabelRightByCurrency: selectLabelRightByAssetKey,
      selectIconByCurrency: selectIconByAssetKey,
      selectLabelMobileByCurrency: selectLabelMobileByAssetKey,
      walletAddress: wallet || '',
      buyPrefill: cashBuyPrefill,
      sellSelectTitleOverride: cashSellSelectTitleOverride,
      sellDestinationMode: cashSellDestinationMode,
    }),
    [
      cashModalTab,
      setCashModalTab,
      walletLabel,
      rlusdPerUnitRates,
      selectLabelByAssetKey,
      selectLabelRightByAssetKey,
      selectIconByAssetKey,
      selectLabelMobileByAssetKey,
      wallet,
      cashBuyPrefill,
      preferredCurrency,
      cashSellSelectTitleOverride,
      cashSellDestinationMode,
    ],
  );

  // --- Activation modal props ---
  const activationModalProps = useMemo(
    () => ({
      onSendFromWallet: handleActivationSendFromWallet,
      onRequestFromThirdParty: handleActivationRequestFromThirdParty,
      onBuyViaMoonpay: handleActivationBuyViaMoonpay,
    }),
    [handleActivationSendFromWallet, handleActivationRequestFromThirdParty, handleActivationBuyViaMoonpay],
  );

  // --- Activation Request modal props ---
  const activationRequestModalProps = useMemo(
    () => ({
      walletAddress: wallet,
    }),
    [wallet],
  );

  // --- Info modal props ---
  const infoModalProps = useMemo(() => ({}), []);

  // --- Statement shared props ---
  const statementSharedProps = useMemo(
    () => ({
      augmentedTokens: displayTokensWithCurrencyLines || augmentedTokens,
      backendWalletAddress,
      wallet,
      walletDisplayLabel: walletHasCustomLabel ? walletLabel : '',
      isWalletActivated,
      hasRlusdTrustline: hasOnChainRlusd,
      rlusdBalance: effectiveCurrencyLinesSummary?.rlusdOnChain ?? null,
      isFullPageView: true,
      statementVariant: 'full',
      usdRates,
      preferredCurrency,
      rlusdPerUnitRates,
      showGlobalStatement,
      setShowGlobalStatement,
      showCurrencyStatement,
      setShowCurrencyStatement,
      selectedStatementToken,
      setSelectedStatementToken,
      statementBalance,
      highlightTransactionId,
      toast,
    }),
    [
      displayTokensWithCurrencyLines,
      augmentedTokens,
      backendWalletAddress,
      wallet,
      walletHasCustomLabel,
      walletLabel,
      isWalletActivated,
      hasOnChainRlusd,
      effectiveCurrencyLinesSummary,
      usdRates,
      preferredCurrency,
      rlusdPerUnitRates,
      showGlobalStatement,
      setShowGlobalStatement,
      showCurrencyStatement,
      setShowCurrencyStatement,
      selectedStatementToken,
      setSelectedStatementToken,
      statementBalance,
      highlightTransactionId,
      toast,
    ],
  );

  // --- RLUSD Setup modal props --- (removed: setup handled by WalletSetupDropdown)

  return {
    sendModalProps,
    receiveModalProps,
    swapModalProps,
    cashModalProps,
    activationModalProps,
    activationRequestModalProps,
    infoModalProps,
    statementSharedProps,

    // open / close handlers needed by both desktop & mobile
    activeAction,
    setActiveAction,
    showActivationModal,
    setShowActivationModal,
    showActivationRequestModal,
    setShowActivationRequestModal,
    walletInfoOpen,
    setWalletInfoOpen,
    setSendPaymentRequest,
    setCashBuyPrefill,
    setCashSellSelectTitleOverride,
    setCashSellDestinationMode,
    resetSendForm,
    resetReceiveForm,
    resetSwapForm,
    resetCashForm,
    qrScannerOpen,
    setQrScannerOpen: setQrScannerOpen,
    handleAddressScan,
    handlePaymentRequestScan,

    // Cash modal uses different availableTokens in desktop vs mobile
    selectableTokens,
    augmentedTokens,
  };
}
